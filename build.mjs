// Builds the userscript and the unpacked extension from src/. Outputs are committed.
// Usage: node build.mjs [outDir]   (default: the repo root)
import { readFile, writeFile, mkdir, rm, copyFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('.', import.meta.url));
const src = (p) => readFile(join(ROOT, 'src', p), 'utf8');

export const USERSCRIPT = 'immich-paper-sphere-button.user.js';
export const OUTPUTS = ['extension'];
const RAW_URL = `https://raw.githubusercontent.com/schrauger/immich-paper-sphere-button/main/${USERSCRIPT}`;
const BANNER = '// Generated by build.mjs from src/. Edit those files, then run `npm run build`.\n';

const fill = (text, vars) => text.replace(/\{\{(\w+)\}\}/g, (_, k) => vars[k]);
const stripExports = (code) => code.replace(/^export /gm, '');

/** Wraps parts in one IIFE; content scripts also refuse to run twice in one page. */
function bundle(parts, { once }) {
  const guard = once
    ? 'if (window.__immichPaperSphereButton) return;\nwindow.__immichPaperSphereButton = true;\n\n'
    : '';
  return `${BANNER}(() => {\n'use strict';\n${guard}${parts.join('\n')}})();\n`;
}

export async function build(outDir = ROOT) {
  const { version } = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'));
  const core = stripExports(await src('core.js'));
  const button = await src('button.js');

  const header = fill(await src('userscript/header.txt'), { version, rawUrl: RAW_URL });
  const userscript = header + '\n' + bundle([core, await src('userscript/settings.js'), button], { once: true });
  await writeFile(join(outDir, USERSCRIPT), userscript);

  const ext = join(outDir, 'extension');
  await rm(ext, { recursive: true, force: true });
  await mkdir(ext, { recursive: true });
  await writeFile(join(ext, 'manifest.json'), fill(await src('extension/manifest.json'), { version }));
  await writeFile(join(ext, 'content.js'), bundle([core, await src('extension/content-settings.js'), button], { once: true }));
  await writeFile(join(ext, 'options.js'), bundle([core, await src('extension/options.js')], { once: false }));
  await writeFile(join(ext, 'background.js'), BANNER + await src('extension/background.js'));
  await copyFile(join(ROOT, 'src/extension/options.html'), join(ext, 'options.html'));
  await copyFile(join(ROOT, 'LICENSE'), join(ext, 'LICENSE'));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await build(process.argv[2] ? resolve(process.argv[2]) : ROOT);
  console.log('Built', USERSCRIPT, 'and extension/');
}
